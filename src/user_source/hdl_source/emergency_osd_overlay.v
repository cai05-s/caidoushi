                16: message_id = 15;
                17: message_id = 16;
                18: message_id = 17;
                19: message_id = 18;
                20: message_id = 4;
                21: message_id = 19;
                22: message_id = 20;
                23: message_id = 21;
                24: message_id = 22;
                25: message_id = 23;
                26: message_id = 24;
                default: message_id = 63;
            endcase
        end
    endfunction
