    always @(posedge clk or posedge rst) begin
        if (rst) begin
            emergency_sync1 <= 0; emergency_sync2 <= 0; emergency_frame <= 0;
            scroll_offset <= 0; scroll_div <= 0; blink_count <= 0; blink_on <= 1;
        end else begin
            emergency_sync1 <= emergency_active; emergency_sync2 <= emergency_sync1;
            if (frame_start) begin
                emergency_frame <= emergency_sync2;
                if (!emergency_sync2) begin
                    scroll_offset <= 0; scroll_div <= 0; blink_count <= 0; blink_on <= 1;
                end else begin
                    if (scroll_div >= SCROLL_FRAMES-1) begin
                        scroll_div <= 0;
                        scroll_offset <= scroll_offset >= SCROLL_END-1 ? 0 : scroll_offset+1'b1;
                    end else scroll_div <= scroll_div+1'b1;
                    if (blink_count == 29) begin blink_count <= 0; blink_on <= !blink_on; end
                    else blink_count <= blink_count+1'b1;
                end
            end
        end
    end
