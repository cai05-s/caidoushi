        if (emergency_frame && in_de) begin
            // 字幕仅覆盖顶部48行，其余区域保留疏散图；最高优先级白字。
            if (pixel_y < 48) begin
                rgb_out = {1'b0,rgb_in[23:17],1'b0,rgb_in[15:9],1'b0,rgb_in[7:1]} | 24'h600000;
